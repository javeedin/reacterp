-- ============================================================
-- RR_GL_JE_HEADERS Table
-- Created for ReactERP - Oracle Fusion Data Sync
-- ============================================================

CREATE TABLE RR_GL_JE_HEADERS (
    -- Primary Key
    HEADER_SYNC_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JE_HEADER_ID              NUMBER NOT NULL,

    -- Foreign Key to Batch
    JE_BATCH_ID               NUMBER NOT NULL,
    BATCH_SYNC_ID             NUMBER,

    -- Journal Details
    JE_HEADER_NAME            VARCHAR2(240),
    DESCRIPTION               VARCHAR2(4000),
    PERIOD_NAME               VARCHAR2(15),
    DEFAULT_EFFECTIVE_DATE    DATE,

    -- Ledger Information
    LEDGER_ID                 NUMBER,
    LEDGER_NAME               VARCHAR2(240),
    LEGAL_ENTITY_ID           NUMBER,
    LEGAL_ENTITY_NAME         VARCHAR2(240),

    -- Category and Source
    JE_CATEGORY               VARCHAR2(80),
    USER_JE_CATEGORY_NAME     VARCHAR2(80),
    JE_SOURCE                 VARCHAR2(80),
    USER_JE_SOURCE_NAME       VARCHAR2(80),

    -- Status
    STATUS                    VARCHAR2(30),
    STATUS_MEANING            VARCHAR2(80),
    APPROVAL_STATUS           VARCHAR2(30),
    APPROVAL_STATUS_MEANING   VARCHAR2(80),
    FUNDS_STATUS              VARCHAR2(30),
    FUNDS_STATUS_MEANING      VARCHAR2(80),

    -- Currency
    CURRENCY_CODE             VARCHAR2(15),
    CURRENCY_CONVERSION_TYPE  VARCHAR2(30),
    CURRENCY_CONVERSION_DATE  DATE,
    CURRENCY_CONVERSION_RATE  NUMBER,

    -- Totals - Entered Currency
    RUNNING_TOTAL_DR          NUMBER,
    RUNNING_TOTAL_CR          NUMBER,

    -- Totals - Accounted Currency
    RUNNING_TOTAL_ACCOUNTED_DR NUMBER,
    RUNNING_TOTAL_ACCOUNTED_CR NUMBER,

    -- Reversal Information
    ACCRUAL_REV_CHANGE_FLAG   VARCHAR2(1),
    ACCRUAL_REV_EFF_DATE      DATE,
    ACCRUAL_REV_PERIOD_NAME   VARCHAR2(15),
    ACCRUAL_REV_STATUS        VARCHAR2(30),
    REVERSED_JE_HEADER_ID     NUMBER,

    -- Posting Information
    POSTED_DATE               DATE,
    POSTING_ACCT_SEQ_VALUE    NUMBER,
    CLOSE_ACCT_SEQ_VALUE      NUMBER,

    -- External Reference
    EXTERNAL_REFERENCE        VARCHAR2(240),
    REFERENCE_DATE            DATE,
    TAX_STATUS_CODE           VARCHAR2(30),
    ACTUAL_FLAG               VARCHAR2(1),
    ACTUAL_FLAG_MEANING       VARCHAR2(80),

    -- Budget Information
    BUDGET_VERSION_ID         NUMBER,
    ENCUMBRANCE_TYPE_ID       NUMBER,

    -- Oracle Audit (from Fusion)
    ORACLE_CREATED_BY         VARCHAR2(64),
    ORACLE_CREATION_DATE      TIMESTAMP WITH TIME ZONE,
    ORACLE_LAST_UPDATE_DATE   TIMESTAMP WITH TIME ZONE,
    ORACLE_LAST_UPDATED_BY    VARCHAR2(64),

    -- Sync Tracking
    SYNC_STATUS               VARCHAR2(20) DEFAULT 'SYNCED',
    SYNC_DATE                 TIMESTAMP DEFAULT SYSTIMESTAMP,
    SYNC_ERROR_MESSAGE        VARCHAR2(4000),

    -- Local Audit Columns
    CREATED_BY                VARCHAR2(100) DEFAULT USER,
    CREATION_DATE             TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY           VARCHAR2(100),
    LAST_UPDATE_DATE          TIMESTAMP,

    -- Constraints
    CONSTRAINT UK_RR_GL_HEADERS_JE_HEADER_ID UNIQUE (JE_HEADER_ID),
    CONSTRAINT FK_RR_GL_HEADERS_BATCH FOREIGN KEY (BATCH_SYNC_ID)
        REFERENCES RR_GL_JOURNAL_BATCHES(BATCH_SYNC_ID)
);

-- Create indexes
CREATE INDEX IDX_RR_HDR_BATCH_ID ON RR_GL_JE_HEADERS(JE_BATCH_ID);
CREATE INDEX IDX_RR_HDR_BATCH_SYNC_ID ON RR_GL_JE_HEADERS(BATCH_SYNC_ID);
CREATE INDEX IDX_RR_HDR_PERIOD ON RR_GL_JE_HEADERS(PERIOD_NAME);
CREATE INDEX IDX_RR_HDR_STATUS ON RR_GL_JE_HEADERS(STATUS);
CREATE INDEX IDX_RR_HDR_SOURCE ON RR_GL_JE_HEADERS(USER_JE_SOURCE_NAME);
CREATE INDEX IDX_RR_HDR_CATEGORY ON RR_GL_JE_HEADERS(USER_JE_CATEGORY_NAME);
CREATE INDEX IDX_RR_HDR_LEDGER ON RR_GL_JE_HEADERS(LEDGER_NAME);
CREATE INDEX IDX_RR_HDR_SYNC_DATE ON RR_GL_JE_HEADERS(SYNC_DATE);

COMMENT ON TABLE RR_GL_JE_HEADERS IS 'GL Journal Headers synced from Oracle Fusion';
