-- ============================================================
-- RR_GL_JE_LINES_ALL Table
-- Created for ReactERP - Oracle Fusion Data Sync
-- ============================================================

CREATE TABLE RR_GL_JE_LINES_ALL (
    -- Primary Key
    LINE_SYNC_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JE_LINE_NUM               NUMBER NOT NULL,

    -- Foreign Keys
    JE_HEADER_ID              NUMBER NOT NULL,
    HEADER_SYNC_ID            NUMBER,
    JE_BATCH_ID               NUMBER,

    -- Account Information
    CODE_COMBINATION_ID       NUMBER,
    CONCATENATED_SEGMENTS     VARCHAR2(750),
    SEGMENT1                  VARCHAR2(25),  -- Company
    SEGMENT2                  VARCHAR2(25),  -- Cost Center
    SEGMENT3                  VARCHAR2(25),  -- Account
    SEGMENT4                  VARCHAR2(25),  -- Sub-Account
    SEGMENT5                  VARCHAR2(25),  -- Product
    SEGMENT6                  VARCHAR2(25),  -- Intercompany
    SEGMENT7                  VARCHAR2(25),  -- Future1
    SEGMENT8                  VARCHAR2(25),  -- Future2

    -- Line Details
    DESCRIPTION               VARCHAR2(4000),
    PERIOD_NAME               VARCHAR2(15),
    EFFECTIVE_DATE            DATE,

    -- Amounts - Entered Currency
    ENTERED_DR                NUMBER,
    ENTERED_CR                NUMBER,

    -- Amounts - Accounted (Ledger Currency)
    ACCOUNTED_DR              NUMBER,
    ACCOUNTED_CR              NUMBER,

    -- Currency Information
    CURRENCY_CODE             VARCHAR2(15),
    CURRENCY_CONVERSION_TYPE  VARCHAR2(30),
    CURRENCY_CONVERSION_DATE  DATE,
    CURRENCY_CONVERSION_RATE  NUMBER,

    -- Status
    STATUS                    VARCHAR2(30),
    STATUS_MEANING            VARCHAR2(80),

    -- Statistical
    STAT_AMOUNT               NUMBER,
    STAT_UOM                  VARCHAR2(30),

    -- Reference Information
    REFERENCE1                VARCHAR2(240),
    REFERENCE2                VARCHAR2(240),
    REFERENCE3                VARCHAR2(240),
    REFERENCE4                VARCHAR2(240),
    REFERENCE5                VARCHAR2(240),
    REFERENCE6                VARCHAR2(240),
    REFERENCE7                VARCHAR2(240),
    REFERENCE8                VARCHAR2(240),
    REFERENCE9                VARCHAR2(240),
    REFERENCE10               VARCHAR2(240),

    -- Attributes
    ATTRIBUTE_CATEGORY        VARCHAR2(150),
    ATTRIBUTE1                VARCHAR2(150),
    ATTRIBUTE2                VARCHAR2(150),
    ATTRIBUTE3                VARCHAR2(150),
    ATTRIBUTE4                VARCHAR2(150),
    ATTRIBUTE5                VARCHAR2(150),

    -- Context Information
    CONTEXT                   VARCHAR2(150),
    CONTEXT2                  VARCHAR2(150),
    CONTEXT3                  VARCHAR2(150),

    -- Subledger Accounting
    GL_SL_LINK_ID             NUMBER,
    GL_SL_LINK_TABLE          VARCHAR2(30),
    JE_LINE_ID                NUMBER,

    -- Tax
    TAX_CODE                  VARCHAR2(50),
    TAX_GROUP                 VARCHAR2(60),
    TAXABLE_LINE_FLAG         VARCHAR2(1),

    -- Clearing/Reconciliation
    CLEARED_DATE              DATE,
    RECONCILIATION_REFERENCE  VARCHAR2(240),

    -- Oracle Audit (from Fusion)
    ORACLE_CREATED_BY         VARCHAR2(64),
    ORACLE_CREATION_DATE      TIMESTAMP WITH TIME ZONE,
    ORACLE_LAST_UPDATE_DATE   TIMESTAMP WITH TIME ZONE,
    ORACLE_LAST_UPDATED_BY    VARCHAR2(64),

    -- Sync Tracking
    SYNC_STATUS               VARCHAR2(20) DEFAULT 'SYNCED',
    SYNC_DATE                 TIMESTAMP DEFAULT SYSTIMESTAMP,
    SYNC_ERROR_MESSAGE        VARCHAR2(4000),

    -- Local Audit Columns
    CREATED_BY                VARCHAR2(100) DEFAULT USER,
    CREATION_DATE             TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY           VARCHAR2(100),
    LAST_UPDATE_DATE          TIMESTAMP,

    -- Constraints
    CONSTRAINT FK_RR_GL_LINES_HEADER FOREIGN KEY (HEADER_SYNC_ID)
        REFERENCES RR_GL_JE_HEADERS(HEADER_SYNC_ID)
);

-- Create indexes
CREATE INDEX IDX_RR_LINE_HEADER_ID ON RR_GL_JE_LINES_ALL(JE_HEADER_ID);
CREATE INDEX IDX_RR_LINE_HEADER_SYNC_ID ON RR_GL_JE_LINES_ALL(HEADER_SYNC_ID);
CREATE INDEX IDX_RR_LINE_BATCH_ID ON RR_GL_JE_LINES_ALL(JE_BATCH_ID);
CREATE INDEX IDX_RR_LINE_PERIOD ON RR_GL_JE_LINES_ALL(PERIOD_NAME);
CREATE INDEX IDX_RR_LINE_ACCOUNT ON RR_GL_JE_LINES_ALL(CONCATENATED_SEGMENTS);
CREATE INDEX IDX_RR_LINE_SYNC_DATE ON RR_GL_JE_LINES_ALL(SYNC_DATE);

COMMENT ON TABLE RR_GL_JE_LINES_ALL IS 'GL Journal Lines synced from Oracle Fusion';
